/**
 * Génère les déclarations TypeScript du contenu servi par /okno/v1/export.
 *
 * Les types décrivent exactement ce que renvoie l'API de contenu (et non le
 * stockage ACF) : le front les importe tels quels, `npx okno types` les
 * régénère quand les champs changent.
 */
class Okno_Types {

	/** Au-delà, un select est typé string plutôt qu'en union de littéraux. */
	const MAX_LITERALS = 30;

	/**
	 * Fichier .d.ts complet pour le site.
	 *
	 * @param Okno_Plugin $plugin Plugin.
	 * @return string
	 */
	public static function generate( Okno_Plugin $plugin ) {
		$types = array();
		foreach ( Okno_Content::post_types() as $post_type ) {
			$groups = array();
			foreach ( $plugin->adapters() as $adapter ) {
				if ( $adapter instanceof Okno_Content_Adapter_Interface ) {
					$groups = array_merge( $groups, $adapter->get_definitions( $post_type ) );
				}
			}
			$types[ $post_type ] = $groups;
		}

		return self::render( $types, home_url() );
	}

	/**
	 * Rendu, sans WordPress (testable).
	 *
	 * @param array<string,array> $types  post_type => groupes { conditional, fields }.
	 * @param string              $source URL du CMS, citée en tête de fichier.
	 * @return string
	 */
	public static function render( array $types, $source = '' ) {
		$out   = array();
		$out[] = '// Generated by Okno ' . OKNO_VERSION . ( $source ? ' from ' . $source : '' ) . '. Do not edit: run `npx okno types` again.';
		$out[] = '';
		$out[] = self::base();

		$names = array();
		foreach ( $types as $post_type => $groups ) {
			$name    = self::type_name( $post_type );
			$names[] = $name;

			$fields = array();
			foreach ( $groups as $group ) {
				foreach ( $group['fields'] as $field ) {
					$key = isset( $field['name'] ) ? (string) $field['name'] : '';
					if ( '' === $key || in_array( $field['type'], Okno_ACF_Adapter::LAYOUT_TYPES, true ) ) {
						continue;
					}
					// Champ présent dans un groupe toujours affiché : il gagne.
					$optional = ! empty( $group['conditional'] );
					if ( isset( $fields[ $key ] ) && ! $fields[ $key ]['optional'] ) {
						continue;
					}
					$fields[ $key ] = array(
						'optional' => $optional,
						'type'     => self::field_type( $field, 1 ),
						'label'    => isset( $field['label'] ) ? (string) $field['label'] : '',
					);
				}
			}

			if ( ! $fields ) {
				$out[] = 'export type ' . $name . 'Fields = Record<string, never>;';
			} else {
				$out[] = 'export interface ' . $name . 'Fields {';
				foreach ( $fields as $key => $field ) {
					if ( '' !== $field['label'] ) {
						$out[] = "\t/** " . self::comment( $field['label'] ) . ' */';
					}
					$out[] = "\t" . self::property( $key ) . ( $field['optional'] ? '?' : '' ) . ': ' . $field['type'] . ';';
				}
				$out[] = '}';
			}
			$out[] = '';
			$out[] = 'export type ' . $name . " = OknoItem<'" . $post_type . "', " . $name . 'Fields>;';
			$out[] = '';
		}

		$out[] = 'export type OknoContent = ' . ( $names ? implode( ' | ', $names ) : 'never' ) . ';';
		$out[] = '';
		$out[] = 'export interface OknoExport {';
		$out[] = "\tformat: number;";
		$out[] = "\tversion: string;";
		$out[] = "\tgenerated: string;";
		$out[] = "\tsite: { name: string; front_url: string; cms_url: string; language: string };";
		$out[] = "\titems: OknoContent[];";
		$out[] = '}';
		$out[] = '';

		return implode( "\n", $out );
	}

	/**
	 * Types communs (médias, liens, références, enveloppe d'un contenu).
	 *
	 * @return string
	 */
	private static function base() {
		return <<<'TS'
export interface OknoImageSize {
	url: string;
	width: number | null;
	height: number | null;
}

export interface OknoMedia {
	id: number;
	url: string;
	alt: string;
	title: string;
	mime: string;
	width: number | null;
	height: number | null;
	sizes: Record<string, OknoImageSize>;
}

export interface OknoLink {
	url: string;
	title: string;
	target: string;
}

export interface OknoRef {
	id: number;
	type: string;
	slug: string;
	title: string;
	path: string;
}

export interface OknoTerm {
	id: number;
	slug: string;
	name: string;
	taxonomy: string;
}

export interface OknoItem<TType extends string, TFields> {
	id: number;
	type: TType;
	slug: string;
	status: string;
	/** Path on the front end, e.g. /services/audit. */
	path: string;
	url: string;
	title: string;
	date: string;
	modified: string;
	parent: number | null;
	menu_order: number;
	excerpt: string;
	/** Rendered HTML of the main editor. */
	content: string;
	featured_image: OknoMedia | null;
	terms: Record<string, OknoTerm[]>;
	fields: TFields;
}

TS;
	}

	/**
	 * Type TypeScript d'un champ ACF, tel que servi par l'API de contenu.
	 *
	 * @param array $field Champ ACF brut.
	 * @param int   $depth Indentation courante.
	 * @return string
	 */
	public static function field_type( $field, $depth ) {
		$type = $field['type'];

		switch ( $type ) {
			case 'text':
			case 'textarea':
			case 'wysiwyg':
			case 'url':
			case 'email':
			case 'password':
			case 'oembed':
			case 'color_picker':
			case 'date_picker':
			case 'date_time_picker':
			case 'time_picker':
			case 'page_link':
				return 'string';

			case 'radio':
			case 'button_group':
				return self::choices( $field );

			case 'select':
				return ! empty( $field['multiple'] ) ? self::wrap_array( self::choices( $field ) ) : self::choices( $field );

			case 'checkbox':
				return self::wrap_array( self::choices( $field ) );

			case 'true_false':
				return 'boolean';

			case 'number':
			case 'range':
				return 'number | null';

			case 'image':
			case 'file':
				return 'OknoMedia | null';

			case 'gallery':
				return 'OknoMedia[]';

			case 'link':
				return 'OknoLink | null';

			case 'post_object':
				return ! empty( $field['multiple'] ) ? 'OknoRef[]' : 'OknoRef | null';

			case 'relationship':
				return 'OknoRef[]';

			case 'taxonomy':
				return Okno_ACF_Adapter::taxonomy_is_multiple( $field ) ? 'OknoTerm[]' : 'OknoTerm | null';

			case 'repeater':
				return 'Array<' . self::object( isset( $field['sub_fields'] ) ? $field['sub_fields'] : array(), $depth ) . '>';

			case 'group':
			case 'clone':
				return self::object( isset( $field['sub_fields'] ) ? $field['sub_fields'] : array(), $depth );

			case 'flexible_content':
				$variants = array();
				foreach ( (array) ( isset( $field['layouts'] ) ? $field['layouts'] : array() ) as $layout ) {
					$variants[] = self::object(
						isset( $layout['sub_fields'] ) ? $layout['sub_fields'] : array(),
						$depth + 1,
						"_layout: '" . self::literal( $layout['name'] ) . "'"
					);
				}
				if ( ! $variants ) {
					return 'never[]';
				}
				$indent = str_repeat( "\t", $depth + 1 );
				return "Array<\n" . $indent . '| ' . implode( "\n" . $indent . '| ', $variants ) . "\n" . str_repeat( "\t", $depth ) . '>';

			default:
				return 'unknown';
		}
	}

	/**
	 * Objet littéral pour des sous-champs.
	 *
	 * @param array  $subs  Sous-champs ACF bruts.
	 * @param int    $depth Indentation courante.
	 * @param string $first Propriété à placer en tête (discriminant).
	 * @return string
	 */
	private static function object( $subs, $depth, $first = '' ) {
		$indent = str_repeat( "\t", $depth + 1 );
		$lines  = array();
		if ( '' !== $first ) {
			$lines[] = $indent . $first . ';';
		}
		foreach ( (array) $subs as $sub ) {
			$key = isset( $sub['name'] ) ? (string) $sub['name'] : '';
			if ( '' === $key || in_array( $sub['type'], Okno_ACF_Adapter::LAYOUT_TYPES, true ) ) {
				continue;
			}
			$lines[] = $indent . self::property( $key ) . ': ' . self::field_type( $sub, $depth + 1 ) . ';';
		}
		if ( ! $lines ) {
			return 'Record<string, never>';
		}
		return "{\n" . implode( "\n", $lines ) . "\n" . str_repeat( "\t", $depth ) . '}';
	}

	private static function choices( $field ) {
		$choices = isset( $field['choices'] ) && is_array( $field['choices'] ) ? array_keys( $field['choices'] ) : array();
		if ( ! $choices || count( $choices ) > self::MAX_LITERALS ) {
			return 'string';
		}
		$literals = array();
		foreach ( $choices as $choice ) {
			$literals[] = "'" . self::literal( (string) $choice ) . "'";
		}
		// Champ facultatif non rempli : chaîne vide.
		if ( empty( $field['required'] ) && empty( $field['multiple'] ) && 'checkbox' !== $field['type'] ) {
			$literals[] = "''";
		}
		return implode( ' | ', array_unique( $literals ) );
	}

	private static function wrap_array( $type ) {
		return false === strpos( $type, '|' ) ? $type . '[]' : 'Array<' . $type . '>';
	}

	/**
	 * Nom de type : dyese_service → DyeseService.
	 *
	 * @param string $post_type Type de contenu.
	 * @return string
	 */
	public static function type_name( $post_type ) {
		$name = str_replace( ' ', '', ucwords( preg_replace( '/[^a-z0-9]+/i', ' ', (string) $post_type ) ) );
		if ( '' === $name || ctype_digit( $name[0] ) ) {
			$name = 'Type' . $name;
		}
		return $name;
	}

	private static function property( $key ) {
		return preg_match( '/^[A-Za-z_$][A-Za-z0-9_$]*$/', $key ) ? $key : "'" . self::literal( $key ) . "'";
	}

	private static function literal( $value ) {
		return str_replace( array( '\\', "'", "\n", "\r" ), array( '\\\\', "\\'", '\\n', '' ), (string) $value );
	}

	private static function comment( $text ) {
		return trim( str_replace( array( '*/', "\n", "\r" ), array( '* /', ' ', '' ), $text ) );
	}
}
